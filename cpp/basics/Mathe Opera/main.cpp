#include <iostream>

using namespace std;

int main()
{
    int x = 10;
    int y = 3;

    cout << "Sum: " << x + y << endl;
    cout << "Difference: " << x - y << endl;
    cout << "Multiplication: " << x * y << endl;
    cout << "Division: " << (float)x / y << endl;
    cout << "Remainder: " << x % y << endl;
    return 0;
}
